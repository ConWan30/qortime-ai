"""python -m qortime_ai.redteam [--generate] [--out examples/redteam]"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from qortime_ai.redteam import harness
from qortime_ai.redteam.explain import EXPLANATIONS_PATH, audit, case_inputs


def generate() -> float:
    from qortime_ai.redteam.generate import spark_explain, wonder_attacks

    sb = harness.Sandbox()
    try:
        doc, usd = wonder_attacks(sb.receipt)
        harness.ATTACKS_PATH.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        cases = {}
        for name, (r, v) in case_inputs(sb).items():
            cases[name], u = spark_explain(r, v)
            usd += u
        EXPLANATIONS_PATH.write_text(json.dumps({"schema": "qortime-redteam-explanations/v1", "cases": cases},
                                                indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    finally:
        sb.close()
    return usd


def summary_md(rep: dict) -> str:
    L = [f"# Red-Team the Referee: {rep['headline']}", "",
         f"- Verifier under test: {rep['verifier']}", f"- Keys: {rep['keys']}",
         f"- Attacks generated by: {(rep.get('generator') or {}).get('model')} (cached fixture, replayed offline)",
         f"- Invalid mutations (harness could not apply): {rep['invalid']}; identical to an honest receipt: {rep['no_tamper']}",
         "", "| # | attack | resign / pin | verifier status | first reason |", "|---|---|---|---|---|"]
    for i, r in enumerate(rep["rows"], 1):
        L.append(f"| {i} | `{r['id']}` | {r['resign']} / {r['pin']} | {r['outcome'] if r['outcome'] != 'rejected' else r['status']} | "
                 f"{(r['reasons'] or [''])[0]} |")
    L += ["", "## Cited explanations (Muse Spark; checked by code)", ""]
    for e in rep["explanations"]:
        L.append(f"- **{e['case']}** ({e['verdict']}): " + (" ".join(e["text"].split()) if e["shown"] else
                 "withheld: " + ", ".join(p["problem"] for p in e["problems"])))
    L += ["", "AI never decides the verdict: the verifier does. Explanations are shown only if every sentence cites "
          "existing fields that support it and no banned overclaim word appears."]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m qortime_ai.redteam")
    ap.add_argument("--generate", action="store_true", help="LIVE: call Muse Wonder + Spark and refresh fixtures")
    ap.add_argument("--out", default="examples/redteam")
    a = ap.parse_args(argv)
    if a.generate:
        print(f"generated fixtures, est. ${generate():.4f}")
    rep = harness.run()
    sb = harness.Sandbox()
    try:
        rep["explanations"] = audit(sb)
    finally:
        sb.close()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "report.json").write_text(json.dumps(rep, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "summary.md").write_text(summary_md(rep), encoding="utf-8")
    w = max(len(str(r["id"])) for r in rep["rows"])
    for r in rep["rows"]:
        st = r["outcome"] if r["outcome"] != "rejected" else f"REJECTED {r['status']}"
        print(f"{r['id']:<{w}}  {st:<24} {(r['reasons'] or [''])[0]}")
    for e in rep["explanations"]:
        print(f"explanation[{e['case']}]: {'shown' if e['shown'] else 'withheld ' + str([p['problem'] for p in e['problems']])}")
    print(rep["headline"])
    return 1 if rep["accepted"] else 0


if __name__ == "__main__":
    sys.exit(main())
